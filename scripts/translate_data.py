def translate(text):
    """翻譯文字，優先完全匹配，否則逐字替換"""
    if text in ALL_TRANSLATIONS:
        return ALL_TRANSLATIONS[text]
    # 嘗試子字串替換（用於 chanp.cgi 等混合文字）
    result = text
    for jp, tc in sorted(ALL_TRANSLATIONS.items(), key=lambda x: -len(x[0])):
        result = result.replace(jp, tc)
    return result


def read_sjis(filepath):
    """讀取 Shift_JIS 編碼檔案"""
    with open(filepath, 'rb') as f:
        return f.read().decode('shift_jis', errors='replace')


def process_standard_file(filename, name_field_indices):
    """處理標準 <> 分隔檔案，翻譯指定欄位"""
    src = os.path.join(SOURCE_DIR, filename)
    dst = os.path.join(TARGET_DIR, filename)

    if not os.path.exists(src):
        print(f'  跳過 {filename}（不存在）')
        return

    size = os.path.getsize(src)
    if size == 0:
        # 建立空檔案
        open(dst, 'w').close()
        print(f'  {filename}（空檔案）')
        return

    text = read_sjis(src)
    lines = text.strip().split('\n')
    output_lines = []

    for line in lines:
        if not line.strip():
            continue
        fields = line.split('<>')
        for idx in name_field_indices:
            if idx < len(fields) and fields[idx]:
                fields[idx] = translate(fields[idx])
        output_lines.append('<>'.join(fields))

    with open(dst, 'w', encoding='utf-8') as f:
        f.write('\n'.join(output_lines) + '\n')

    print(f'  {filename}：{len(output_lines)} 行')


def process_ability_file():
    """處理 ability.cgi（欄位 1=名稱, 2=說明）"""
    process_standard_file('ability.cgi', [1, 2])


def process_chanp_file():
    """處理 chanp.cgi（整行翻譯）"""
    src = os.path.join(SOURCE_DIR, 'chanp.cgi')
    dst = os.path.join(TARGET_DIR, 'chanp.cgi')

    if not os.path.exists(src) or os.path.getsize(src) == 0:
        open(dst, 'w').close()
        print(f'  chanp.cgi（空或不存在）')
        return

    text = read_sjis(src)
    translated = translate(text)

    with open(dst, 'w', encoding='utf-8') as f:
        f.write(translated)

    print(f'  chanp.cgi：已翻譯')


